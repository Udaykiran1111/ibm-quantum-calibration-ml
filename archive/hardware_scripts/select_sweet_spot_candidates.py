def load_predictions():
    """
    Load ALL predictions generated by the temporal Sweet-Spot
    notebook and retain only:

        model_name      = temporal_30day
        window_days     = 30
        prediction_date = 2026-09-06

    The resulting dataframe should contain approximately
    466 rows:

        FEZ       ~155
        Kingston  ~155
        Marrakesh  156
    """

    print(
        "Loading Sweet-Spot predictions..."
    )

    if not PREDICTIONS_FILE.exists():

        raise FileNotFoundError(
            "\n"
            "Missing Sweet-Spot prediction file:\n\n"
            f"{PREDICTIONS_FILE}\n\n"
            "Expected:\n"
            "results/sweet_spot/"
            "sep6_all_temporal_model_predictions.csv"
        )

    df = pd.read_csv(
        PREDICTIONS_FILE
    )

    print(
        f"Raw prediction rows: "
        f"{len(df):,}"
    )

    # --------------------------------------------------------
    # Required columns
    # --------------------------------------------------------

    required_columns = {
        "model_name",
        "window_days",
        "prediction_date",
        "backend",
        "qubit",
        "viability_score",
    }

    missing_columns = (
        required_columns
        - set(df.columns)
    )

    if missing_columns:

        raise RuntimeError(
            "\n"
            "Prediction file is missing required columns:\n"
            f"{sorted(missing_columns)}\n\n"
            "Available columns:\n"
            f"{list(df.columns)}"
        )

    # --------------------------------------------------------
    # Normalize fields
    # --------------------------------------------------------

    df["model_name"] = (
        df["model_name"]
        .astype(str)
        .str.strip()
    )

    df["window_days"] = pd.to_numeric(
        df["window_days"],
        errors="coerce",
    )

    df["prediction_date"] = (
        pd.to_datetime(
            df["prediction_date"],
            errors="coerce",
        )
        .dt.strftime("%Y-%m-%d")
    )

    df["backend"] = (
        df["backend"]
        .astype(str)
        .str.strip()
    )

    df["qubit"] = pd.to_numeric(
        df["qubit"],
        errors="coerce",
    )

    df["viability_score"] = pd.to_numeric(
        df["viability_score"],
        errors="coerce",
    )

    # --------------------------------------------------------
    # Remove invalid rows
    # --------------------------------------------------------

    df = df.dropna(
        subset=[
            "model_name",
            "window_days",
            "prediction_date",
            "backend",
            "qubit",
            "viability_score",
        ]
    ).copy()

    df["window_days"] = (
        df["window_days"]
        .astype(int)
    )

    df["qubit"] = (
        df["qubit"]
        .astype(int)
    )

    df["viability_score"] = (
        df["viability_score"]
        .astype(float)
    )

    # --------------------------------------------------------
    # Select final 30-day Sweet-Spot model
    # --------------------------------------------------------

    df = df[
        (df["model_name"] == MODEL_NAME)
        &
        (df["window_days"] == WINDOW_DAYS)
        &
        (
            df["prediction_date"]
            == PREDICTION_DATE
        )
        &
        df["backend"].isin(
            BACKENDS
        )
    ].copy()

    if df.empty:

        raise RuntimeError(
            "\n"
            "No predictions found after filtering.\n\n"
            f"Model           : {MODEL_NAME}\n"
            f"Window          : {WINDOW_DAYS} days\n"
            f"Prediction date : {PREDICTION_DATE}\n"
        )

    # --------------------------------------------------------
    # Duplicate check
    # --------------------------------------------------------

    duplicate_mask = df.duplicated(
        subset=[
            "backend",
            "qubit",
        ],
        keep=False,
    )

    if duplicate_mask.any():

        duplicate_rows = (
            df[
                duplicate_mask
            ]
            .sort_values(
                [
                    "backend",
                    "qubit",
                ]
            )
        )

        raise RuntimeError(
            "\n"
            "Duplicate backend/qubit predictions found:\n\n"
            f"{duplicate_rows.to_string(index=False)}"
        )

    # --------------------------------------------------------
    # Validation output
    # --------------------------------------------------------

    print(
        "Sweet-Spot prediction filter: PASS"
    )

    print(
        f"Filtered predictions: "
        f"{len(df):,}"
    )

    for backend_name in BACKENDS:

        count = int(
            (
                df["backend"]
                == backend_name
            ).sum()
        )

        print(
            f"  {backend_name}: "
            f"{count} predicted qubits"
        )

    return df


# ============================================================
# BUILD PHYSICAL 3-QUBIT CHAINS
# ============================================================

def build_three_qubit_chains(
    backend
):
    """
    Build all unique physically connected 3-qubit chains.

    A valid chain has:

        q1 ---- q2 ---- q3

    where q1-q2 and q2-q3 are both physically connected.

    Coupling-map direction is ignored because this stage is
    checking physical connectivity, not gate direction.
    """

    coupling_map = (
        backend.configuration()
        .coupling_map
    )

    adjacency = {
        q: set()
        for q in range(
            backend.num_qubits
        )
    }

    # --------------------------------------------------------
    # Build undirected adjacency graph
    # --------------------------------------------------------

    for edge in coupling_map:

        if len(edge) != 2:
            continue

        q1 = int(
            edge[0]
        )

        q2 = int(
            edge[1]
        )

        if q1 == q2:
            continue

        adjacency[q1].add(
            q2
        )

        adjacency[q2].add(
            q1
        )

    # --------------------------------------------------------
    # Enumerate q1-q2-q3 chains
    # --------------------------------------------------------

    chains = set()

    for middle in range(
        backend.num_qubits
    ):

        neighbors = sorted(
            adjacency[middle]
        )

        if len(neighbors) < 2:
            continue

        for i in range(
            len(neighbors)
        ):

            for j in range(
                i + 1,
                len(neighbors)
            ):

                left = neighbors[i]

                right = neighbors[j]

                chain = tuple(
                    sorted(
                        [
                            left,
                            middle,
                            right,
                        ]
                    )
                )

                chains.add(
                    chain
                )

    return sorted(
        chains
    )


# ============================================================
# SCORE PHYSICAL CHAINS
# ============================================================

def score_physical_chains(
    chains,
    score_lookup,
):
    """
    Score every physical chain for which all three qubits
    have a Sweet-Spot prediction.

    Chain score:

        mean(q1, q2, q3)

    Secondary criterion:

        minimum(q1, q2, q3)
    """

    scored_chains = []

    missing_prediction_chains = 0

    for chain in chains:

        # ----------------------------------------------------
        # Require predictions for ALL three qubits.
        # ----------------------------------------------------

        if not all(
            q in score_lookup
            for q in chain
        ):

            missing_prediction_chains += 1

            continue

        scores = [
            float(
                score_lookup[q]
            )
            for q in chain
        ]

        mean_viability = (
            sum(scores)
            / 3.0
        )

        minimum_viability = min(
            scores
        )

        scored_chains.append(
            {
                "qubits":
                    list(chain),

                "scores":
                    scores,

                "mean_viability":
                    mean_viability,

                "minimum_viability":
                    minimum_viability,
            }
        )

    return (
        scored_chains,
        missing_prediction_chains,
    )


# ============================================================
# SELECT BEST SWEET-SPOT CHAIN
# ============================================================

def select_best_chain(
    scored_chains
):
    """
    Select the best physical chain.

    Primary:
        highest mean viability.

    Secondary:
        highest minimum viability.
    """

    if not scored_chains:
        return None

    scored_chains.sort(
        key=lambda item: (
            item["mean_viability"],
            item["minimum_viability"],
        ),
        reverse=True,
    )

    return scored_chains[0]


# ============================================================
# SELECT RANDOM CONTROLS
# ============================================================

def select_random_controls(
    all_chains,
    sweet_spot_chain,
    seed,
):
    """
    Select mutually independent random control chains.

    Requirements:

    1. Every control must be a valid physical 3Q chain.
    2. No control may overlap the Sweet-Spot chain.
    3. No random controls may overlap each other.
    4. Exactly RANDOM_TRIALS controls are returned.
    """

    # --------------------------------------------------------
    # Sweet-Spot qubits
    # --------------------------------------------------------

    sweet_qubits = set(
        int(q)
        for q in sweet_spot_chain
    )

    # --------------------------------------------------------
    # Remove every physical chain that touches the
    # Sweet-Spot chain.
    # --------------------------------------------------------

    available_chains = []

    for chain in all_chains:

        chain_set = set(
            int(q)
            for q in chain
        )

        if (
            chain_set
            & sweet_qubits
        ):
            continue

        available_chains.append(
            tuple(chain)
        )

    # --------------------------------------------------------
    # Randomize candidate order.
    # --------------------------------------------------------

    rng = random.Random(
        seed
    )

    rng.shuffle(
        available_chains
    )

    # --------------------------------------------------------
    # Greedily select mutually disjoint controls.
    # --------------------------------------------------------

    selected = []

    used_random_qubits = set()

    for chain in available_chains:

        chain_set = set(
            int(q)
            for q in chain
        )

        # Don't allow overlap with another random control.
        if (
            chain_set
            & used_random_qubits
        ):
            continue

        selected.append(
            chain
        )

        used_random_qubits.update(
            chain_set
        )

        if len(selected) >= RANDOM_TRIALS:
            break

    # --------------------------------------------------------
    # Final validation
    # --------------------------------------------------------

    if len(selected) < RANDOM_TRIALS:

        raise RuntimeError(
            "\n"
            f"Could not construct "
            f"{RANDOM_TRIALS} mutually disjoint "
            "random controls.\n\n"
            f"Topology-valid chains       : "
            f"{len(all_chains)}\n"
            f"Chains after Sweet-Spot     : "
            f"{len(available_chains)}\n"
            f"Controls successfully found : "
            f"{len(selected)}"
        )

    # --------------------------------------------------------
    # Validate Sweet-Spot independence
    # --------------------------------------------------------

    for chain in selected:

        chain_set = set(
            chain
        )

        if (
            chain_set
            & sweet_qubits
        ):

            raise RuntimeError(
                "Internal validation failure: "
                "random control overlaps Sweet-Spot chain."
            )

    # --------------------------------------------------------
    # Validate random-control independence
    # --------------------------------------------------------

    seen = set()

    for chain in selected:

        chain_set = set(
            chain
        )

        if (
            chain_set
            & seen
        ):

            raise RuntimeError(
                "Internal validation failure: "
                "random controls overlap each other."
            )

        seen.update(
            chain_set
        )

    return selected


