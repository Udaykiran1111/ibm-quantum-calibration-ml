def main():

    print("=" * 72)

    print(
        "IBM CIRCUIT BENCH"
    )

    print(
        "SWEET-SPOT CANDIDATE SELECTION"
    )

    print("=" * 72)

    print()

    print(
        "Experiment model : "
        "Temporal 30-day Sweet-Spot"
    )

    print(
        f"Prediction date  : "
        f"{PREDICTION_DATE}"
    )

    print(
        f"Random controls  : "
        f"{RANDOM_TRIALS}/backend"
    )

    print(
        "QPU execution    : NONE"
    )

    print()

    # ========================================================
    # LOAD PREDICTIONS
    # ========================================================

    predictions = (
        load_predictions()
    )

    print()

    # ========================================================
    # CONNECT TO IBM
    # ========================================================

    service = connect_ibm()

    # ========================================================
    # OUTPUT STORAGE
    # ========================================================

    csv_rows = []

    json_backends = []

    # ========================================================
    # PROCESS EACH BACKEND
    # ========================================================

    for backend_index, backend_name in enumerate(
        BACKENDS
    ):

        print()

        print("=" * 72)

        print(
            f"BACKEND: {backend_name}"
        )

        print("=" * 72)

        # ----------------------------------------------------
        # Get backend
        # ----------------------------------------------------

        backend = service.backend(
            backend_name
        )

        # ----------------------------------------------------
        # Build physical topology
        # ----------------------------------------------------

        chains = (
            build_three_qubit_chains(
                backend
            )
        )

        print(
            f"Physical qubits : "
            f"{backend.num_qubits}"
        )

        print(
            f"Valid 3Q chains : "
            f"{len(chains)}"
        )

        # ----------------------------------------------------
        # Get predictions for backend
        # ----------------------------------------------------

        backend_predictions = (
            predictions[
                predictions["backend"]
                == backend_name
            ]
            .copy()
        )

        if backend_predictions.empty:

            raise RuntimeError(
                f"No Sweet-Spot predictions "
                f"found for {backend_name}."
            )

        print(
            f"Predicted qubits: "
            f"{len(backend_predictions)}"
        )

        # ----------------------------------------------------
        # Build qubit -> viability lookup
        # ----------------------------------------------------

        score_lookup = dict(
            zip(
                backend_predictions[
                    "qubit"
                ].astype(int),

                backend_predictions[
                    "viability_score"
                ].astype(float),
            )
        )

        # ----------------------------------------------------
        # Score all physical chains
        # ----------------------------------------------------

        (
            scored_chains,
            missing_prediction_chains,
        ) = score_physical_chains(
            chains,
            score_lookup,
        )

        print(
            f"Chains with complete predictions: "
            f"{len(scored_chains)}"
        )

        print(
            f"Chains missing predictions       : "
            f"{missing_prediction_chains}"
        )

        if not scored_chains:

            raise RuntimeError(
                "\n"
                f"No physically connected 3-qubit "
                f"chain has predictions for all "
                f"three qubits on {backend_name}.\n\n"
                f"Physical chains : {len(chains)}\n"
                f"Predicted qubits: {len(score_lookup)}"
            )

        # ----------------------------------------------------
        # Select Sweet-Spot chain
        # ----------------------------------------------------

        sweet_spot = (
            select_best_chain(
                scored_chains
            )
        )

        print()

        print(
            "SWEET-SPOT CHAIN"
        )

        print(
            f"  Qubits          : "
            f"{sweet_spot['qubits']}"
        )

        print(
            f"  Scores          : "
            f"{[round(x, 6) for x in sweet_spot['scores']]}"
        )

        print(
            f"  Mean viability  : "
            f"{sweet_spot['mean_viability']:.6f}"
        )

        print(
            f"  Minimum score   : "
            f"{sweet_spot['minimum_viability']:.6f}"
        )

        # ----------------------------------------------------
        # Select random controls
        # ----------------------------------------------------

        random_controls = (
            select_random_controls(
                chains,
                sweet_spot["qubits"],
                RANDOM_SEED
                + backend_index,
            )
        )

        print()

        print(
            "RANDOM CONTROLS"
        )

        for trial_index, chain in enumerate(
            random_controls,
            start=1,
        ):

            print(
                f"  Random {trial_index:02d}: "
                f"{list(chain)}"
            )

        # ----------------------------------------------------
        # Explicit validation output
        # ----------------------------------------------------

        sweet_set = set(
            sweet_spot["qubits"]
        )

        random_sets = []

        for chain in random_controls:

            chain_set = set(
                chain
            )

            random_sets.append(
                chain_set
            )

        sweet_overlap = any(
            bool(
                chain_set
                & sweet_set
            )
            for chain_set
            in random_sets
        )

        random_overlap = False

        for i in range(
            len(random_sets)
        ):

            for j in range(
                i + 1,
                len(random_sets)
            ):

                if (
                    random_sets[i]
                    & random_sets[j]
                ):

                    random_overlap = True

        if sweet_overlap:

            raise RuntimeError(
                f"{backend_name}: random control "
                "overlaps Sweet-Spot chain."
            )

        if random_overlap:

            raise RuntimeError(
                f"{backend_name}: random controls "
                "overlap each other."
            )

        print()

        print(
            "CONTROL INDEPENDENCE: PASS"
        )

        # ====================================================
        # SAVE SWEET-SPOT CSV ROW
        # ====================================================

        csv_rows.append(
            {
                "prediction_date":
                    PREDICTION_DATE,

                "backend":
                    backend_name,

                "selection_type":
                    "sweet_spot",

                "model_name":
                    MODEL_NAME,

                "window_days":
                    WINDOW_DAYS,

                "qubits":
                    str(
                        sweet_spot[
                            "qubits"
                        ]
                    ),

                "viability_scores":
                    str(
                        sweet_spot[
                            "scores"
                        ]
                    ),

                "mean_viability":
                    sweet_spot[
                        "mean_viability"
                    ],

                "minimum_viability":
                    sweet_spot[
                        "minimum_viability"
                    ],

                "random_trial":
                    None,
            }
        )

        # ====================================================
        # SAVE RANDOM CSV ROWS
        # ====================================================

        for trial_index, chain in enumerate(
            random_controls,
            start=1,
        ):

            csv_rows.append(
                {
                    "prediction_date":
                        PREDICTION_DATE,

                    "backend":
                        backend_name,

                    "selection_type":
                        "random_control",

                    "model_name":
                        "random",

                    "window_days":
                        None,

                    "qubits":
                        str(
                            list(chain)
                        ),

                    "viability_scores":
                        None,

                    "mean_viability":
                        None,

                    "minimum_viability":
                        None,

                    "random_trial":
                        trial_index,
                }
            )

        # ====================================================
        # SAVE JSON BACKEND RECORD
        # ====================================================

        json_backends.append(
            {
                "backend":
                    backend_name,

                "physical_qubits":
                    int(
                        backend.num_qubits
                    ),

                "valid_3q_chains":
                    len(chains),

                "predicted_qubits":
                    len(
                        backend_predictions
                    ),

                "chains_with_complete_predictions":
                    len(
                        scored_chains
                    ),

                "sweet_spot":
                    {
                        "qubits":
                            sweet_spot[
                                "qubits"
                            ],

                        "viability_scores":
                            sweet_spot[
                                "scores"
                            ],

                        "mean_viability":
                            sweet_spot[
                                "mean_viability"
                            ],

                        "minimum_viability":
                            sweet_spot[
                                "minimum_viability"
                            ],
                    },

                "random_controls":
                    [
                        {
                            "trial":
                                trial_index,

                            "qubits":
                                list(
                                    chain
                                ),
                        }

                        for trial_index, chain
                        in enumerate(
                            random_controls,
                            start=1,
                        )
                    ],
            }
        )

    # ========================================================
    # CREATE RESULTS DIRECTORY
    # ========================================================

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ========================================================
    # SAVE CSV
    # ========================================================

    result_df = pd.DataFrame(
        csv_rows
    )

    result_df.to_csv(
        OUTPUT_CSV,
        index=False,
    )

    # ========================================================
    # SAVE JSON
    # ========================================================

    result_json = {
        "experiment":
            "sweet_spot_vs_random",

        "model_name":
            MODEL_NAME,

        "window_days":
            WINDOW_DAYS,

        "prediction_date":
            PREDICTION_DATE,

        "random_trials_per_backend":
            RANDOM_TRIALS,

        "random_seed":
            RANDOM_SEED,

        "random_controls_disjoint_from_sweet_spot":
            True,

        "random_controls_mutually_disjoint":
            True,

        "qpu_execution":
            False,

        "qpu_runtime_seconds":
            0,

        "backends":
            json_backends,
    }

    with open(
        OUTPUT_JSON,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            result_json,
            file,
            indent=2,
        )

    # ========================================================
    # FINAL SUMMARY
    # ========================================================

    print()

    print("=" * 72)

    print(
        "SELECTION COMPLETE"
    )

    print("=" * 72)

    print()

    for record in json_backends:

        sweet = (
            record[
                "sweet_spot"
            ]
        )

        print(
            f"{record['backend']}: "
            f"{sweet['qubits']} | "
            f"mean viability = "
            f"{sweet['mean_viability']:.6f}"
        )

    print()

    print(
        f"CSV saved : "
        f"{OUTPUT_CSV}"
    )

    print(
        f"JSON saved: "
        f"{OUTPUT_JSON}"
    )

    print()

    print(
        "Random controls: "
        "mutually disjoint and Sweet-Spot-disjoint"
    )

    print(
        "QPU usage: 0 seconds"
    )

    print(
        "Candidate selection: PASS"
    )


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":

    main()